#!/usr/bin/env bash
# Apply the Catppuccin Mocha accent named in theme/accent: write the small
# files Waybar, hyprlock and zellij read (generated, so gitignored), then
# print the accent's hex. hyprland.lua runs this on every load and takes the
# border colour from that output, and install.sh runs it on a new machine.
# On a bad name it writes nothing, so the last good accent stays in place.
set -euo pipefail

REPO_DIR="$(dirname "$(dirname "$(realpath "$0")")")"
readonly REPO_DIR

# Catppuccin Mocha's 14 accents (https://catppuccin.com/palette), in its order
readonly NAMES="rosewater flamingo pink mauve red maroon peach yellow green teal sky sapphire blue lavender"
declare -rA MOCHA=(
  [rosewater]=f5e0dc [flamingo]=f2cdcd [pink]=f5c2e7 [mauve]=cba6f7
  [red]=f38ba8 [maroon]=eba0ac [peach]=fab387 [yellow]=f9e2af
  [green]=a6e3a1 [teal]=94e2d5 [sky]=89dceb [sapphire]=74c7ec
  [blue]=89b4fa [lavender]=b4befe
)

die() {
  printf 'apply-accent: %s\n' "$*" >&2
  exit 1
}

# Replace DEST with stdin in one rename, so an app never reads half a file
write() {
  local dest=$1 tmp
  tmp=$(mktemp "$dest.XXXXXX")
  cat >"$tmp"
  mv "$tmp" "$dest"
}

mapfile -t lines < <(grep -v -E '^[[:space:]]*(#|$)' "$REPO_DIR/theme/accent")
((${#lines[@]} == 1)) ||
  die "theme/accent must name exactly one accent, it has ${#lines[@]} lines"
accent=${lines[0]//[[:space:]]/}
# Checked before the lookup: only a bare lowercase word may reach the subscript
[[ "$accent" =~ ^[a-z]+$ && -v "MOCHA[$accent]" ]] ||
  die "unknown accent '$accent' in theme/accent; pick one of: $NAMES"

hex=${MOCHA[$accent]}
rgb="$((16#${hex:0:2})) $((16#${hex:2:2})) $((16#${hex:4:2}))"
notice="Generated by theme/apply-accent.sh from theme/accent ($accent): edit that file."

write "$REPO_DIR/waybar/accent.css" <<EOF
/* $notice */
@define-color accent #$hex;
EOF

write "$REPO_DIR/hypr/accent.conf" <<EOF
# $notice
\$accent = rgba(${hex}ff)
EOF

mkdir -p "$REPO_DIR/zellij/themes"
sed "s/@ACCENT@/$rgb/" "$REPO_DIR/theme/zellij-catppuccin-mocha-accent.kdl.in" |
  write "$REPO_DIR/zellij/themes/catppuccin-mocha-accent.kdl"

printf '%s\n' "$hex"
